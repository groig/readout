defmodule Readout.Documents.Page do
  @moduledoc """
  One page of a processed version: its size (PDF points, for layout before the
  image loads) and its extracted text (search now, AI later). The `search`
  tsvector column is generated by Postgres.
  """
  use Ecto.Schema

  @primary_key {:id, :binary_id, autogenerate: true}
  @foreign_key_type :binary_id
  schema "document_pages" do
    field :number, :integer
    field :width, :float
    field :height, :float
    field :text, :string, default: ""

    belongs_to :version, Readout.Documents.Version
  end
end
